#include "PPPheaders.h"

int main() // C++ programs start by executing the function main
{
  std::cout << "Air-Fryer Cookies!\n";
  std::cout << "Whenever you need a sugar fix, these cookies can be made in minutes from ingreadients that you probably already have in your storecupboard.\n";
  std::cout << "You can use whatever type of chocolate chips you like, or make then rainbow with Smarties.\n\n";
  std::cout << "Cooking time: 8 minutes.\n";
  std::cout << "Preparation time: 15 minutes.\n";
  std::cout << "Calories: 215 kcals per cookie.\n\n";
  std::cout << "Ingreadients:\n";
  std::cout << "220g unsalted butter, softened.\n";
  std::cout << "100g soft brown sugar.\n";
  std::cout << "50g granulated white sugar.\n";
  std::cout << "1 egg, at room temperature.\n";
  std::cout << "1 teaspoon vanilla extract.\n";
  std::cout << "180g plain flour, sifted.\n";
  std::cout << "1 teaspoon baking powder.\n";
  std::cout << "1/2 teaspoon salt.\n";
  std::cout << "130g milk chocolate chips.\n";
  std::cout << "130g dark chocolate chips.\n\n";
  std::cout << "Instructions:\n";
  std::cout << "1.  First, place the butter in a mixing bowl. Add both the brown sugar and white suger, egg and vanilla extract to the bown and mix well to combine with the softened butter.\n";
  std::cout << "2.  Next, add flour, baking powder, salt and both milk and dark chocolate chips. Combine everything to make a soft cookie dough.\n";
  std::cout << "3.  Wrap the cookie dough in clingfilm and chill in the fridge for 30 minutes.\n";
  std::cout << "4.  When ready to cook, preheat the air fryer to 160°C.\n";
  std::cout << "5.  Divide the cookie dough into 20 equal-sized balls and flatten them slightly. You can use an ice-cream scoop to portion out the dough so that the cookies are all roughly the same size. If you don't want to bake all the cookies at the same time, portion out the number of cookies that you need, then wrap any remaining cookie dough in clingfilm and store it in the freezer for baking on another day.\n";
  std::cout << "6.  Line the air pryer. Working in batches, depending on the size of your air fryer, place the cookies in the air fryer. Leave some space around each cookie to allow for them to expand. Cook at 160°C for 8 minutes or until golden.\n";
  std::cout << "7.  Leave the cookies in the air fryer to cool with the door or drawer closed so they continue to cook all the way through to the middle.\n";
  return 0;
}
